func (t Translator) Message(key string) string { return t.Text(Key(key), nil) }
func (t Translator) ProtocolError(code string) string {
	if _, exists := catalogs[t.language][Key("error."+code)]; exists {
		return t.Message("error." + code)
	}
	return t.Text(UnknownError, map[string]any{"Code": code})
}
